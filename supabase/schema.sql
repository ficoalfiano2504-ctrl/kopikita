create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price integer not null check (price >= 0),
  description text not null default '',
  available boolean not null default true,
  image text not null default ''
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  table_number text not null,
  notes text not null default '',
  status text not null default 'Baru' check (status in ('Baru', 'Diterima', 'Diproses', 'Siap', 'Selesai')),
  created_at timestamptz not null default now(),
  is_delivered boolean not null default false,
  delivered_at timestamptz,
  items jsonb not null check (jsonb_typeof(items) = 'array')
);

drop function if exists public.get_customer_order_status(uuid);
alter table public.orders drop column if exists tracking_token;
alter table public.orders add column if not exists is_delivered boolean not null default false;
alter table public.orders add column if not exists delivered_at timestamptz;

alter table public.menu_items enable row level security;
alter table public.orders enable row level security;
